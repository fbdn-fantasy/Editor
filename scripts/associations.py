"""Generate the optional Windows file associations for the per-user installer."""
from pathlib import Path
extensions = """txt text log md markdown json jsonc xml yaml yml toml ini cfg conf csv tsv
html htm css scss js mjs cjs jsx ts mts cts tsx svelte py pyw rs c h cpp cc cxx hpp
hxx cs java kt kts go php rb swift sql sh bash zsh fish ps1 psm1 lua dart r dockerfile mk
gitconfig gitignore gitattributes properties env""".split()
p = Path(__file__).resolve().parents[1] / "packaging/associations.nsh"
prog = r"Software\Classes\Editor.TextDocument"
app = r"Software\Editor\Capabilities"
lines = [
    "; Generated by scripts/associations.py",
    "!macro NSIS_HOOK_POSTINSTALL",
    f'  WriteRegStr HKCU "{prog}" "" "Text document"',
    f'  WriteRegStr HKCU "{prog}\\DefaultIcon" "" \'"$INSTDIR\\editor.exe",0\'',
    f'  WriteRegStr HKCU "{prog}\\shell\\open\\command" "" \'"$INSTDIR\\editor.exe" "%1"\'',
    f'  WriteRegStr HKCU "{app}" "ApplicationName" "Editor"',
    f'  WriteRegStr HKCU "{app}" "ApplicationDescription" "Text and source-code editor"',
    f'  WriteRegStr HKCU "Software\\RegisteredApplications" "Editor" "{app}"',
]
for ext in extensions:
    lines += [f'  WriteRegStr HKCU "Software\\Classes\\.{ext}\\OpenWithProgids" "Editor.TextDocument" ""',
              f'  WriteRegStr HKCU "{app}\\FileAssociations" ".{ext}" "Editor.TextDocument"']
refresh = "  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'"
lines += [refresh, "!macroend", "", "!macro NSIS_HOOK_POSTUNINSTALL"]
for ext in extensions:
    lines.append(f'  DeleteRegValue HKCU "Software\\Classes\\.{ext}\\OpenWithProgids" "Editor.TextDocument"')
lines += [f'  DeleteRegKey HKCU "{prog}"',f'  DeleteRegKey HKCU "{app}"',
          '  DeleteRegKey /ifempty HKCU "Software\\Editor"',
          '  DeleteRegValue HKCU "Software\\RegisteredApplications" "Editor"',refresh,"!macroend"]
p.write_text("\n".join(lines) + "\n")
