"""Generate the optional Windows file associations for the per-user installer."""
from pathlib import Path
extensions = """txt text log md markdown json jsonc xml yaml yml toml ini cfg conf csv tsv
html htm css scss js mjs cjs jsx ts mts cts tsx svelte py pyw rs c h cpp cc cxx hpp
hxx cs java kt kts go php rb swift sql sh bash zsh fish ps1 psm1 lua dart r dockerfile mk
gitconfig gitignore gitattributes properties env""".split()
# Windows uses a single dot as the association key for extensionless files.
extensions.append("")
p = Path(__file__).resolve().parents[1] / "packaging/associations.nsh"
prog = r"Software\Classes\Editor.TextDocument"
app = r"Software\Editor\Capabilities"
application = r"Software\Classes\Applications\editor.exe"
open_verb = r"Software\Classes\*\shell\Editor.Open"
empty_prog = r"Software\Classes\Editor.EmptyDocument"
empty_type = r"Software\Classes\.editordoc"
icon = r'"$INSTDIR\editor.exe",0'
open_command = r'"$INSTDIR\editor.exe" -- "%1"'
lines = [
    "; Generated by scripts/associations.py",
    "!macro NSIS_HOOK_POSTINSTALL",
    f'  WriteRegStr HKCU "{prog}" "" "Text document"',
    f'  WriteRegStr HKCU "{prog}\\DefaultIcon" "" \'{icon}\'',
    f'  WriteRegStr HKCU "{prog}\\shell\\open\\command" "" \'{open_command}\'',
    f'  WriteRegStr HKCU "{prog}\\Application" "ApplicationName" "Editor"',
    f'  WriteRegStr HKCU "{application}" "FriendlyAppName" "Editor"',
    f'  WriteRegStr HKCU "{application}\\DefaultIcon" "" \'{icon}\'',
    f'  WriteRegStr HKCU "{application}\\shell\\open\\command" "" \'{open_command}\'',
    f'  WriteRegStr HKCU "{open_verb}" "" "Open with Editor"',
    f'  WriteRegStr HKCU "{open_verb}" "Icon" \'{icon}\'',
    f'  WriteRegStr HKCU "{open_verb}\\command" "" \'{open_command}\'',
    f'  WriteRegStr HKCU "{app}" "ApplicationName" "Editor"',
    f'  WriteRegStr HKCU "{app}" "ApplicationIcon" \'{icon}\'',
    f'  WriteRegStr HKCU "{app}" "ApplicationDescription" "Text and source-code editor"',
    f'  WriteRegStr HKCU "Software\\RegisteredApplications" "Editor" "{app}"',
]
lines += [
    f'  WriteRegStr HKCU "{empty_prog}" "" "Empty Document"',
    f'  WriteRegStr HKCU "{empty_prog}\\DefaultIcon" "" \'{icon}\'',
    f'  WriteRegStr HKCU "{empty_prog}\\shell\\open\\command" "" \'{open_command}\'',
    f'  WriteRegStr HKCU "{empty_prog}\\Application" "ApplicationName" "Editor"',
    f'  WriteRegStr HKCU "{empty_type}\\ShellNew" "NullFile" ""',
    f'  WriteRegStr HKCU "{empty_type}\\OpenWithProgids" "Editor.EmptyDocument" ""',
    f'  WriteRegStr HKCU "{app}\\FileAssociations" ".editordoc" "Editor.EmptyDocument"',
]
defaults = {".editordoc": "Editor.EmptyDocument", ".": "Editor.TextDocument"}
for extension, progid in defaults.items():
    lines += [f'  ReadRegStr $R0 HKCR "{extension}" ""',
              '  ${If} $R0 == ""',
              f'    WriteRegStr HKCU "Software\\Classes\\{extension}" "" "{progid}"',
              '  ${EndIf}']
for ext in extensions:
    lines += [f'  WriteRegStr HKCU "Software\\Classes\\.{ext}\\OpenWithProgids" "Editor.TextDocument" ""',
              f'  WriteRegStr HKCU "{app}\\FileAssociations" ".{ext}" "Editor.TextDocument"']
refresh = "  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'"
lines += [refresh, "!macroend", "", "!macro NSIS_HOOK_POSTUNINSTALL"]
for ext in extensions:
    lines.append(f'  DeleteRegValue HKCU "Software\\Classes\\.{ext}\\OpenWithProgids" "Editor.TextDocument"')
lines += [f'  DeleteRegValue HKCU "{empty_type}\\ShellNew" "NullFile"',
          f'  DeleteRegKey /ifempty HKCU "{empty_type}\\ShellNew"',
          f'  DeleteRegValue HKCU "{empty_type}\\OpenWithProgids" "Editor.EmptyDocument"',
          f'  DeleteRegKey /ifempty HKCU "{empty_type}\\OpenWithProgids"']
for extension, progid in defaults.items():
    key = f"Software\\Classes\\{extension}"
    lines += [f'  ReadRegStr $R0 HKCU "{key}" ""',
              f'  ${{If}} $R0 == "{progid}"',
              f'    DeleteRegValue HKCU "{key}" ""',
              '  ${EndIf}', f'  DeleteRegKey /ifempty HKCU "{key}"']
for key in [prog, app, open_verb, empty_prog]:
    lines.append(f'  DeleteRegKey HKCU "{key}"')
# Explorer may also have recorded values for editor.exe. Remove our entries only.
lines += [f'  DeleteRegValue HKCU "{application}" "FriendlyAppName"',
          f'  DeleteRegKey HKCU "{application}\\DefaultIcon"',
          f'  DeleteRegKey HKCU "{application}\\shell\\open\\command"',
          f'  DeleteRegKey /ifempty HKCU "{application}\\shell\\open"',
          f'  DeleteRegKey /ifempty HKCU "{application}\\shell"',
          f'  DeleteRegKey /ifempty HKCU "{application}"',
          '  DeleteRegKey /ifempty HKCU "Software\\Editor"',
          '  DeleteRegValue HKCU "Software\\RegisteredApplications" "Editor"',refresh,"!macroend"]
p.write_text("\n".join(lines) + "\n")
